-- The public/anon role receives SELECT only; writes remain available to service_role.

alter table clans enable row level security;
alter table players enable row level security;
alter table player_snapshots enable row level security;
alter table wars enable row level security;
alter table war_participants enable row level security;
alter table war_attacks enable row level security;
alter table cwl_seasons enable row level security;
alter table cwl_rounds enable row level security;
alter table capital_raids enable row level security;

